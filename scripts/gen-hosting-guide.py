def make_table(story, headers, rows, ratios, caption_text=None, center_cols=None):
    center_cols = center_cols or []
    width_used = 0.95 * AVAIL_W
    col_widths = [r * width_used for r in ratios]
    assert abs(sum(ratios) - 1.0) < 0.01, "ratios must sum to 1"
    assert sum(col_widths) <= AVAIL_W + 0.5, "table exceeds available width"
    data = [[Paragraph("<b>%s</b>" % htxt, th_style) for htxt in headers]]
    for row in rows:
        cells = []
        for ci, cell in enumerate(row):
            st = td_c if ci in center_cols else td_style
            cells.append(Paragraph(cell, st))
        data.append(cells)
    t = Table(data, colWidths=col_widths, hAlign="CENTER", repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i),
                      colors.white if i % 2 == 1 else TABLE_STRIPE))
    t.setStyle(TableStyle(style))
    story.append(Spacer(1, 10))
    if caption_text and len(rows) <= 15:
        story.extend(safe_keep_together([t, Paragraph(caption_text, caption)]))
    else:
        story.append(t)
        if caption_text:
            story.append(Paragraph(caption_text, caption))
    story.append(Spacer(1, 10))


def code_block(story, lines, label=None):
    inner = []
