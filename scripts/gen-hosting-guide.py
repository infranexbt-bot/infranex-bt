class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, "bookmark_name"):
            level = getattr(flowable, "bookmark_level", 0)
            text = getattr(flowable, "bookmark_text", "")
            key = getattr(flowable, "bookmark_key", "")
            self.notify("TOCEntry", (level, text, self.page, key))


def add_heading(text, style, level=0):
    key = "h_%s" % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def safe_keep_together(elements, max_ratio=0.4):
    total_h = 0
    for el in elements:
        w, hh = el.wrap(AVAIL_W, PAGE_H)
        total_h += hh
    if total_h <= PAGE_H * max_ratio:
        return [KeepTogether(elements)]
    elif len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)


def chapter(story, text, first_para=None):
    """H1 with accent underline; conditional page break to avoid orphan headings."""
    story.append(CondPageBreak(H1_THRESHOLD))
    head = add_heading(text, h1, level=0)
    rule = HRFlowable(width="100%", color=ACCENT, thickness=1.2, spaceBefore=2, spaceAfter=10)
    block = [head, rule]
    if first_para is not None:
        block.append(Paragraph(first_para, body))
    story.extend(safe_keep_together(block))


def section(story, text, level=1):
    if level == 1:
        story.extend(safe_keep_together([add_heading(text, h2, level=1)]))
    else:
        story.extend(safe_keep_together([Paragraph("<b>%s</b>" % text, h3)]))


