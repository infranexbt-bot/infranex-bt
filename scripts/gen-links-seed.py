#!/usr/bin/env python3
"""
Generate src/lib/infranex/subnet-links-seed.ts from
tool-results/subnet-links.json (built by scripts/enrich-social-links.ts).

The seed bakes the subnetalpha-style social links (Website / X / GitHub /
Discord) into the app bundle so every subnet card + detail dialog can render
the link row with zero runtime fetches. Regenerate after re-running the
enrichment scrape.
"""
import json

SRC = "/home/z/my-project/tool-results/subnet-links.json"
OUT = "/home/z/my-project/src/lib/infranex/subnet-links-seed.ts"

d = json.load(open(SRC))
entries = d["entries"]
cov = d["coverage"]


def esc(s):
    return (s or "").replace("\\", "\\\\").replace('"', '\\"')


lines = []
lines.append("// AUTO-GENERATED by scripts/gen-links-seed.py — do not edit by hand.")
lines.append(f"// Source: finney SubnetIdentitiesV3 + SubnetOverride + README/website")
lines.append(f"// enrichment scrape ({cov['total']} chain-registered subnets; generated")
lines.append(f"// {d['generatedAt']}). Regenerate after re-running scripts/enrich-social-links.ts.")
lines.append("")
lines.append("export interface SubnetLinksSeedEntry {")
lines.append("  name: string;")
lines.append("  github: string | null;")
lines.append("  website: string | null;")
lines.append("  twitter: string | null;")
lines.append("  discord: string | null;")
lines.append('  /** twitter/discord/website provenance: chain | db | readme | website */')
lines.append("  sources: Record<string, string>;")
lines.append("}")
lines.append("")
lines.append("export const SUBNET_LINKS_SEED: Record<number, SubnetLinksSeedEntry> = {")
for netuid in sorted(entries, key=lambda x: int(x)):
    e = entries[netuid]
    parts = [f'name: "{esc(e.get("name"))}"']
    for k in ("github", "website", "twitter", "discord"):
        v = e.get(k)
        parts.append(f'{k}: "{esc(v)}"' if v else f"{k}: null")
    src = e.get("sources") or {}
    src_json = json.dumps(src, separators=(",", ":")) if src else "{}"
    parts.append(f"sources: {src_json}")
    lines.append(f"  {netuid}: {{ {', '.join(parts)} }},")
lines.append("};")
lines.append("")
lines.append(f"/** Number of chain-registered subnets the seed covers. */")
lines.append(f"export const SUBNET_LINKS_SEED_COUNT = {cov['total']};")
lines.append("")

with open(OUT, "w") as f:
    f.write("\n".join(lines))
print(f"wrote {OUT} ({cov['total']} entries)")
